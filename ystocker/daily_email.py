def _num(value: Any, spec: str) -> Optional[str]:
    try:
        return format(float(value), spec)
    except (TypeError, ValueError):
        return None


def _chg(value: Any, dec: int = 2, unit: str = "%") -> str:
    """A signed change in the up/down ink; zero in neither, and a dash for none."""
    try:
        x = float(value)
    except (TypeError, ValueError):
        return f'<span style="color:{_DIM}">—</span>'
    colour = _UP if x > 0 else _DOWN if x < 0 else _DIM
    return f'<span style="color:{colour}">{"+" if x > 0 else ""}{x:.{dec}f}{unit}</span>'


_TH = (f"padding:0 10px 8px;font-size:11px;font-weight:700;letter-spacing:.06em;"
       f"text-transform:uppercase;color:{_DIM};border-bottom:1px solid {_LINE}")
_TD = f"padding:9px 10px;font-size:14px;line-height:1.4;color:{_TEXT};border-bottom:1px solid {_ROW}"


def _table(cols: list[tuple[str, str]], rows: list[list[str]]) -> str:
    """A full-width data table. ``cols`` is (label, "left"|"right"); a cell is
    HTML the caller has already escaped. The first column is the row's name,
    set bright; right-aligned columns are figures, set in tabular numerals and
    never broken across lines."""
    head = "".join(f'<th align="{a}" style="{_TH};text-align:{a}">{_esc(label)}</th>'
                   for label, a in cols)
    body = []
    for i, row in enumerate(rows):
        cells = []
        for j, (cell, (_, align)) in enumerate(zip(row, cols)):
            style = _TD
            if i == len(rows) - 1:
                style += ";border-bottom:0"
            if j == 0:
                style += f";color:{_BRIGHT};font-weight:600"
            if align == "right":
                style += ";text-align:right;white-space:nowrap;font-variant-numeric:tabular-nums"
            cells.append(f'<td align="{align}" valign="top" style="{style}">{cell}</td>')
        body.append("<tr>" + "".join(cells) + "</tr>")
    return ('<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" '
            f'style="border-collapse:collapse;width:100%"><tr>{head}</tr>{"".join(body)}</table>')


def _section(label: str, inner: str) -> str:
    """One block of the mail: a label in the accent ink, then its content."""
    return (f'<tr><td style="padding:26px 24px 0">'
            f'<div style="margin:0 0 12px;font-size:12px;font-weight:700;letter-spacing:.08em;'
            f'text-transform:uppercase;color:{_ACCENT}">{_esc(label)}</div>{inner}</td></tr>')


def _button(href: str, label: str) -> str:
    """A button that renders everywhere: a coloured table cell around a link,
    since Outlook ignores padding on an <a>."""
    return ('<table role="presentation" cellpadding="0" cellspacing="0" border="0"><tr>'
            f'<td bgcolor="#f1f5f9" style="border-radius:8px;background:#f1f5f9">'
            f'<a href="{_esc(href)}" style="display:inline-block;padding:11px 18px;'
            f'font-size:14px;font-weight:600;line-height:1.2;color:{_BG};text-decoration:none;'
            f'border-radius:8px">{_esc(label)}</a></td></tr></table>')


def _header(brand_name: str, lang: str, today_iso: str, site: str) -> str:
    """The masthead: report_email's mark and wordmark, then what this is and when.
    A two-cell table, since Outlook's Word engine supports neither flex nor float."""
    return (
        '<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0"><tr>'
        f'<td width="44" valign="top" style="width:44px;padding:0 14px 0 0">{_mail._logo()}</td>'
        '<td valign="middle">'
        f'<div style="margin:0 0 2px;font-size:21px;font-weight:700;letter-spacing:-.01em;line-height:1.2">'
        f'<a href="{_esc(site)}" style="color:#ffffff;text-decoration:none">{_esc(brand_name)}</a></div>'
        f'<div style="color:#bfdbfe;font-size:14px;line-height:1.4">{_esc(_t(lang, "title"))}</div>'
        f'<div style="margin:2px 0 0;color:#93c5fd;font-size:12px;line-height:1.5">'
        f'{_esc(day_label(today_iso, lang, weekday=True))}</div>'
        '</td></tr></table>')


