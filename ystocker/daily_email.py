def build_all(sites: Iterable[str], summaries_us: dict, summaries_cn: dict, *,
              fallback_lang: str = "en", **data: Any) -> dict[tuple[str, str], dict[str, str]]:
    """Every mail a send needs: ``{(site, lang): mail}`` for each site and both
    languages. A language with no commentary of its own borrows
    ``fallback_lang``'s, as the old builder did, rather than going out without."""
    out = {}
    for site in {(s or default_site()).rstrip("/") for s in sites} or {default_site()}:
        for lang in ("en", "zh"):
            out[(site, lang)] = build(
                lang, site,
                summary_us=summaries_us.get(lang) or summaries_us.get(fallback_lang, ""),
                summary_cn=summaries_cn.get(lang) or summaries_cn.get(fallback_lang, ""),
                **data)
    return out


def unsubscribe(site: str, token: str, lang: str) -> tuple[str, str]:
    """The per-reader line: (html, text). A one-off send carries no token."""
    if token:
        url = f"{(site or default_site()).rstrip('/')}/unsubscribe?token={token}"
        label = _t(lang, "unsubscribe")
        return (f'<a href="{_esc(url)}" style="color:{_DIM};font-size:11px;'
                f'text-decoration:underline">{_esc(label)}</a>', f"{label}: {url}")
    note = _t(lang, "one_off")
    return f'<span style="color:{_DIM};font-size:11px">{_esc(note)}</span>', note


def send_all(ses_client, recipients: Iterable[dict], mails: dict[tuple[str, str], dict[str, str]],
             ses_from: str) -> tuple[int, list[str]]:
    """Send each recipient the mail for their site and language, with their own
    unsubscribe line. Returns (sent, failed addresses); a failure is logged and
    skipped, never raised, so one bad address cannot stop the broadcast.

    ``ses_client`` is passed in -- boto3's in production, a fake in the tests.
    """
    import logging

    log = logging.getLogger(__name__)
    sent, errors = 0, []
    for rec in recipients:
        lang = "zh" if rec.get("lang") == "zh" else "en"
        site = (rec.get("site") or default_site()).rstrip("/")
        mail = mails.get((site, lang)) or mails.get((site, "en")) or next(iter(mails.values()))
        unsub_html, unsub_text = unsubscribe(site, rec.get("token", ""), lang)
        try:
            ses_client.send_email(
                Source=ses_from,
                Destination={"ToAddresses": [rec["email"]]},
                Message={
                    "Subject": {"Data": mail["subject"], "Charset": "UTF-8"},
                    "Body": {
                        "Html": {"Data": mail["html_tmpl"].replace("__UNSUB__", unsub_html),
                                 "Charset": "UTF-8"},
                        "Text": {"Data": f"{mail['text_base']}\n{unsub_text}", "Charset": "UTF-8"},
                    },
                },
            )
            sent += 1
            log.info("Daily report sent to %s (lang=%s site=%s)", rec["email"], lang, site)
        except Exception as exc:  # noqa: BLE001 - one address must not stop the rest
            log.warning("SES send failed for %s: %s", rec["email"], exc)
            errors.append(rec["email"])
    return sent, errors
