def site_for_host(host: Optional[str]) -> str:
    """The site a request came in on, as the base a mail's links use.

    trade-agents.com's two names are one site; any other host is itself, over
    https (nginx terminates TLS, so Flask never sees the scheme). "" for a local
    host, which no reader's mail should ever link to.
    """
    h = (host or "").split(":")[0].strip().lower()
    if not h or h in ("localhost", "127.0.0.1", "0.0.0.0"):
        return ""
    try:
        from ystocker import TA_HOSTS
    except Exception:  # noqa: BLE001 - never fail a mail over branding
        TA_HOSTS = {"trade-agents.com", "www.trade-agents.com"}
    return TA_SITE if h in TA_HOSTS else f"https://{h}"


def default_site() -> str:
    """The site for a subscriber with none recorded -- everyone who subscribed
    before sites were: APP_BASE_URL if set, else yStocker's host. The fallback
    it replaces, ystocker.com, is not a domain this box serves, so an
    unsubscribe link built on it could not have worked."""
    return (os.environ.get("APP_BASE_URL") or YS_SITE).rstrip("/")


def brand(site: str) -> str:
    """TradeAgents or yStocker, by the site the mail links to (report_email's
    rule, so the two mails cannot disagree about one host)."""
    return _mail.brand_for(site)


def day_label(today_iso: str, lang: str, weekday: bool = False) -> str:
    """"September 30, 2026" / "2026年9月30日", optionally with the weekday."""
    try:
        d = date.fromisoformat(today_iso)
    except (TypeError, ValueError):
        return str(today_iso or "")
    if lang == "zh":
        text = f"{d.year}年{d.month}月{d.day}日"
        return f"{text} {_WEEKDAYS_ZH[d.weekday()]}" if weekday else text
    text = f"{_MONTHS_EN[d.month - 1]} {d.day}, {d.year}"
    return f"{_WEEKDAYS_EN[d.weekday()]}, {text}" if weekday else text


def daily_url(site: str, lang: str) -> str:
    return f"{site}/daily?lang={'zh' if lang == 'zh' else 'en'}"


