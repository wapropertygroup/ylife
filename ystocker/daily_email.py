def _commentary(label: str, text: str) -> str:
    return _section(label, _mail.render(text)) if (text or "").strip() else ""


def _indices(indices: dict, lang: str) -> str:
    rows = []
    for key, en, zh in _INDICES:
        d = (indices or {}).get(key) or {}
        last = _num(d.get("current"), ",.2f")
        if last is None:
            continue
        rows.append([_esc(zh if lang == "zh" else en), last, _chg(d.get("day_chg"))])
    if not rows:
        return ""
    return _section(_t(lang, "indices"), _table(
        [(_t(lang, "index"), "left"), (_t(lang, "last"), "right"), (_t(lang, "day"), "right")], rows))


def _metrics(vix: dict, sentiment: dict, lang: str) -> str:
    fg = (sentiment or {}).get("fg") or {}
    pcr = (sentiment or {}).get("pcr") or {}
    aaii = (sentiment or {}).get("aaii") or {}
    dim = f'<span style="color:{_DIM};font-size:13px">{{}}</span>'
    rows = []
    v = _num((vix or {}).get("current"), ".2f")
    if v is not None:
        rows.append([_esc(_t(lang, "vix")), v, _chg((vix or {}).get("day_chg"))])
    v = _num(pcr.get("current"), ".2f")
    if v is not None:
        ma = _num(pcr.get("ma20"), ".2f")
        rows.append([_esc(_t(lang, "pcr")), v,
                     dim.format(_esc(_t(lang, "pcr_ma").format(v=ma))) if ma else ""])
    v = _num(fg.get("score"), ".0f")
    if v is not None:
        rating = str(fg.get("rating") or "")
        if lang == "zh":
            rating = _FG_ZH.get(rating.strip().lower(), rating)
        rows.append([_esc(_t(lang, "fg")), v, dim.format(_esc(rating))])
    v = _num(aaii.get("bullish"), ".1f")
    if v is not None:
        rows.append([_esc(_t(lang, "aaii_bull")), f"{v}%", ""])
    v = _num(aaii.get("bearish"), ".1f")
    if v is not None:
        rows.append([_esc(_t(lang, "aaii_bear")), f"{v}%", ""])
    if aaii.get("bull_bear_spread") is not None:
        rows.append([_esc(_t(lang, "aaii_spread")), _chg(aaii.get("bull_bear_spread"), 1), ""])
    if not rows:
        return ""
    return _section(_t(lang, "metrics"), _table(
        [(_t(lang, "indicator"), "left"), (_t(lang, "reading"), "right"), (_t(lang, "note"), "right")],
        rows))


def _sectors(sectors: list, lang: str) -> str:
    ranked = sorted((s for s in (sectors or []) if s.get("label")),
                    key=lambda s: s.get("day_chg") if s.get("day_chg") is not None else -999,
                    reverse=True)
    if not ranked:
        return ""
    weekly = any(s.get("week_chg_pct") is not None for s in ranked)
    cols = [(_t(lang, "sector"), "left"), (_t(lang, "day"), "right")]
    if weekly:
        cols.append((_t(lang, "week"), "right"))
    rows = []
    for s in ranked:
        label = s["label"]
        name = _SECTORS_ZH.get(label, label) if lang == "zh" else label
        row = [_esc(name), _chg(s.get("day_chg"))]
        if weekly:
            row.append(_chg(s.get("week_chg_pct"), 1))
        rows.append(row)
    return _section(_t(lang, "sectors"), _table(cols, rows))


def _commodities(gold: dict, lang: str) -> str:
    g = gold or {}
    rows = []
    v = _num(g.get("gold_price"), ",.0f")
    if v is not None:
        rows.append([_esc(_t(lang, "gold")), f"${v}", ""])
    v = _num(g.get("silver_price"), ",.2f")
    if v is not None:
        rows.append([_esc(_t(lang, "silver")), f"${v}", ""])
    v = _num(g.get("current_gs"), ".1f")
    if v is not None:
        rows.append([_esc(_t(lang, "gs")), v, _chg(g.get("gs_day_chg"))])
    v = _num(g.get("current_gc"), ".1f")
    if v is not None:
        rows.append([_esc(_t(lang, "gc")), v, _chg(g.get("gc_day_chg"))])
    if not rows:
        return ""
    return _section(_t(lang, "commodities"), _table(
        [(_t(lang, "commodity"), "left"), (_t(lang, "value"), "right"), (_t(lang, "day"), "right")],
        rows))


def _events(events: list, today_iso: str, lang: str) -> str:
    """The next high-impact events -- or, on a quiet calendar, the next ones."""
    upcoming = [e for e in (events or []) if (e.get("date") or "") >= (today_iso or "")]
    shown = [e for e in upcoming if e.get("impact") == "High"][:8] or upcoming[:8]
    rows = []
    for e in shown:
        when = (e.get("date") or "")[5:]
        if e.get("time"):
            when = f"{when} {e['time']}".strip()
        name = (e.get("zh") if lang == "zh" and e.get("zh") else e.get("event")) or ""
        country = e.get("country") or ""
        if lang == "zh":
            country = _COUNTRY_ZH.get(country, country)
        cell = _esc(name)
        if country:
            cell = f'<span style="color:{_DIM}">{_esc(country)}</span> · {cell}'
        en, zh, colour = _IMPACT.get(e.get("impact") or "", (e.get("impact") or "", e.get("impact") or "", _DIM))
        impact = f'<span style="color:{colour};font-weight:600">{_esc(zh if lang == "zh" else en)}</span>'
        rows.append([f'<span style="font-weight:500">{_esc(when)}</span>', cell, impact])
    if not rows:
        return ""
    return _section(_t(lang, "events"), _table(
        [(_t(lang, "when"), "left"), (_t(lang, "event"), "left"), (_t(lang, "impact"), "right")], rows))


def _movers(movers: list, label_key: str, lang: str) -> str:
    rows = []
    for m in movers or []:
        ticker = m.get("ticker") or ""
        if not ticker:
            continue
        name = (m.get("name") or "")[:40]
        cell = _esc(ticker)
        if name:
            cell += (f'<br><span style="color:{_DIM};font-size:12px;font-weight:400">'
                     f'{_esc(name)}</span>')
        price = _num(m.get("price"), ",.2f")
        rows.append([cell, f"${price}" if price else "—", _chg(m.get("day_chg"))])
    if not rows:
        return ""
    return _section(_t(lang, label_key), _table(
        [(_t(lang, "stock"), "left"), (_t(lang, "price"), "right"), (_t(lang, "day"), "right")], rows))


