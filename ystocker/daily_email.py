"""
ystocker.daily_email
~~~~~~~~~~~~~~~~~~~~
The daily markets email: the subscriber broadcast after the US close and the
one-off "Send" on /daily. Pure -- data in, strings out -- so every layout choice
here is testable without an app, a network or SES (tests/test_daily_email.py).

It replaced a builder in routes.py that laid the mail out 1,200px wide, set the
two AI commentaries in side-by-side table cells -- which cannot reflow, so on a
phone each became a column about 180px wide -- inserted the commentary
unescaped, with any Markdown as literal asterisks, dated the Chinese edition
"September 30, 2026", named sectors and events in English in it, and signed
every mail yStocker whatever site the reader had subscribed on. The content is
unchanged: the two short prose commentaries from /api/daily-summary, and the
day's tables.

Rules, each for a client that breaks without it:

* **640px, one column, tables for layout.** Outlook's Word engine supports
  neither flex nor float, and a phone cannot reflow table cells set side by
  side, so every block is a full-width row, stacked.
* **Inline styles only.** Gmail drops a <style> block. The palette and the mark
  are report_email.py's, so the two mails this site sends read as one sender's.
* **The commentary is escaped Markdown.** report_email.render() is the
  email-safe port of static/markdown.js: text is escaped before any tag is
  added, and **bold** arrives bold.
* **Dark, and it says so.** ``color-scheme: dark`` keeps Apple Mail from
  inverting a mail that is already dark into a washed-out light one.
* **Linked to the reader's own site.** A subscriber's site is recorded when they
  subscribe (site_for_host); the brand and every link follow it.
"""
